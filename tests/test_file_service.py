"""TXT formatting, safety gates, encoding, and real-graph-to-export checks."""

from copy import deepcopy
from unittest.mock import Mock

import pytest

from models.vocabulary_model import DefinitionBatch, IdentifiedWord, WordSelection
from services.file_service import (
    DEFINITIONS_FILENAME, DEFINITIONS_MIME, FileGenerationError,
    generate_definitions_file, validate_workflow_result,
)
from workflows.vocabulary_workflow import run_vocabulary_workflow


@pytest.fixture
def completed_result():
    passage = "The café’s intricate décor inspired perseverance."
    words = [IdentifiedWord(word=word, original_context=passage, difficulty_level="Intermediate")
             for word in ("intricate", "perseverance")]
    entries = [
        {**words[0].model_dump(), "definition": "Having many small, connected details — not simple.",
         "example_sentence": "The artist’s intricate sketch impressed Zoë."},
        {**words[1].model_dump(), "definition": "Continuing to try despite difficulty.",
         "example_sentence": "Her perseverance helped her learn French."},
    ]
    llm = Mock(request_structured=Mock(side_effect=[
        WordSelection(identified_words=words), DefinitionBatch(entries=list(reversed(entries))),
    ]))
    state = run_vocabulary_workflow(passage, llm=llm)
    assert state["validation_status"] == "valid"
    return state, llm


def test_format_order_unicode_and_no_extra_calls(completed_result, tmp_path, monkeypatch):
    state, llm = completed_result
    before = deepcopy(state)
    monkeypatch.chdir(tmp_path)
    data = generate_definitions_file(state)
    text = data.decode("utf-8")
    assert DEFINITIONS_FILENAME == "Definitions.txt"
    assert DEFINITIONS_MIME == "text/plain"
    assert text.startswith("VOCABULARY BUILDER AGENT\r\n" + "=" * 30)
    assert "Your Personalized Vocabulary List" in text
    assert "Difficulty Level: Intermediate" in text
    assert "Total Words Identified: 2" in text
    assert text.index("1. intricate") < text.index("2. perseverance")
    assert text.count("Definition:") == 2
    assert text.count("Example Sentence:") == 2
    assert text.count("Original Context:") == 2
    assert "Zoë" in text and "café’s" in text and "—" in text
    assert "\n" not in text.replace("\r\n", "")
    assert text.endswith("Generated by Vocabulary Builder Agent\r\n")
    assert not list(tmp_path.iterdir())
    assert data == generate_definitions_file(state)
    assert llm.request_structured.call_count == 2
    assert state == before


@pytest.mark.parametrize("status", ["pending", "invalid", "failed"])
def test_unvalidated_results_rejected(completed_result, status):
    state, _ = completed_result
    state["validation_status"] = status
    with pytest.raises(FileGenerationError):
        generate_definitions_file(state)


@pytest.mark.parametrize("key, value", [
    ("error_message", "Failure"), ("validation_errors", ["invalid"]),
    ("generation_errors", ["bad schema"]), ("max_words", 1),
    ("selected_difficulty", "Advanced"), ("total_words_analyzed", 999),
    ("stage_status", {}), ("original_text", "Different text."),
    ("identified_words", []), ("generated_definitions", []),
])
def test_inconsistent_result_rejected(completed_result, key, value):
    state, _ = completed_result
    state[key] = value
    with pytest.raises(FileGenerationError):
        generate_definitions_file(state)


@pytest.mark.parametrize("field, value", [
    ("definition", ""), ("example_sentence", " "), ("word", "unrelated"),
    ("original_context", "Invented context."), ("difficulty_level", "Advanced"),
])
def test_mutated_pydantic_instances_are_revalidated(completed_result, field, value):
    state, _ = completed_result
    setattr(state["generated_definitions"][0], field, value)
    with pytest.raises(FileGenerationError):
        generate_definitions_file(state)


@pytest.mark.parametrize("field", ["identified_words", "generated_definitions"])
def test_duplicates_rejected(completed_result, field):
    state, _ = completed_result
    state[field].append(state[field][0])
    with pytest.raises(FileGenerationError):
        generate_definitions_file(state)


def test_generated_order_is_restored(completed_result):
    state, _ = completed_result
    state["generated_definitions"].reverse()
    text = generate_definitions_file(state).decode("utf-8")
    assert text.index("1. intricate") < text.index("2. perseverance")


def test_empty_success_has_no_file():
    llm = Mock(request_structured=Mock(return_value=WordSelection(identified_words=[])))
    state = run_vocabulary_workflow("A simple day.", llm=llm)
    assert validate_workflow_result(state) == []
    with pytest.raises(FileGenerationError, match="no vocabulary words"):
        generate_definitions_file(state)
    llm.request_structured.assert_called_once()


@pytest.mark.parametrize("result", [None, {}, [], {"validation_status": "valid"}])
def test_malformed_result_has_safe_error(result):
    with pytest.raises(FileGenerationError, match="saved analysis"):
        generate_definitions_file(result)


def test_unencodable_text_has_safe_error(completed_result):
    state, _ = completed_result
    state["generated_definitions"][0].definition = "Invalid character \ud800"
    with pytest.raises(FileGenerationError, match="saved analysis"):
        generate_definitions_file(state)
