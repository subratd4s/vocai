"""Validate and format completed workflow results as an in-memory UTF-8 TXT file."""

from collections.abc import Mapping

from agents.validator import validate_definitions, validate_words
from models.vocabulary_model import DefinitionBatch, DifficultyLevel, VocabularyEntry, WordSelection
from utils.helpers import count_words

DEFINITIONS_FILENAME = "Definitions.txt"
DEFINITIONS_MIME = "text/plain"


class FileGenerationError(ValueError):
    """Safe export errors suitable for display without provider or input details."""


def validate_workflow_result(result: Mapping) -> list[VocabularyEntry]:
    """Recheck a final snapshot before rendering/export; allow valid empty results.

    The status flag alone is insufficient: revalidate schema, source grounding,
    completeness, difficulty, and stage outcomes using the existing validators.
    """
    try:
        if not isinstance(result, Mapping) or result.get("validation_status") != "valid":
            raise ValueError
        if any(result.get(key) for key in ("error_message", "error_kind", "validation_errors", "generation_errors")):
            raise ValueError
        original = result["original_text"]
        maximum = result["max_words"]
        if not isinstance(original, str) or not original.strip():
            raise ValueError
        if type(maximum) is not int or not 1 <= maximum <= 20:
            raise ValueError
        if type(result["total_words_analyzed"]) is not int or result["total_words_analyzed"] != count_words(original):
            raise ValueError
        level = DifficultyLevel(result["selected_difficulty"])
        selection = WordSelection.model_validate({"identified_words": result["identified_words"]})
        batch = DefinitionBatch.model_validate({"entries": result["generated_definitions"]})
        if selection.identified_words != validate_words(selection, original, level, maximum):
            raise ValueError
        report = validate_definitions(batch, selection.identified_words, original, maximum)
        if report.validation_status != "valid":
            raise ValueError
        stages = result["stage_status"]
        if stages["Text Analysis"] != "Completed" or stages["Word Identification"] != "Completed":
            raise ValueError
        if selection.identified_words:
            if stages["Definition Generation"] != "Completed" or stages["Validation"] != "Passed":
                raise ValueError
        elif stages["Definition Generation"] != "Skipped" or stages["Validation"] != "Skipped":
            raise ValueError
        by_word = {entry.word.casefold(): entry for entry in batch.entries}
        return [by_word[word.word.casefold()] for word in selection.identified_words]
    except (KeyError, TypeError, ValueError, AttributeError):
        raise FileGenerationError(
            "The saved analysis is incomplete or has not passed validation. Please analyze the passage again."
        ) from None


def generate_definitions_file(result: Mapping) -> bytes:
    """Return Windows-compatible UTF-8 bytes; never write files or call an LLM."""
    entries = validate_workflow_result(result)
    if not entries:
        raise FileGenerationError("There are no vocabulary words to export.")
    level = DifficultyLevel(result["selected_difficulty"])
    lines = [
        "VOCABULARY BUILDER AGENT", "=" * 30, "",
        "Your Personalized Vocabulary List", "",
        f"Difficulty Level: {level.value}", f"Total Words Identified: {len(entries)}",
        "", "=" * 30, "",
    ]
    for number, entry in enumerate(entries, 1):
        lines.extend([
            f"{number}. {entry.word}", "", "Definition:", entry.definition, "",
            "Original Context:", entry.original_context, "",
            "Example Sentence:", entry.example_sentence, "",
            f"Difficulty: {entry.difficulty_level.value}", "",
            "-" * 30 if number < len(entries) else "=" * 30, "",
        ])
    lines.extend(["Generated by Vocabulary Builder Agent", ""])
    # Preserve punctuation/Unicode and normalize line endings once for Windows.
    text = "\n".join(lines).replace("\r\n", "\n").replace("\r", "\n")
    try:
        return text.replace("\n", "\r\n").encode("utf-8")
    except UnicodeError:
        raise FileGenerationError("The vocabulary text could not be encoded for download. Please analyze the passage again.") from None
